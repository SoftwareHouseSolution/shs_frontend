/* Regenerates components/chrome/preloaderMark.ts — the SWH mark, embedded as data URIs:
   the ink "S" for the light theme and the off-white "S" for the dark one.

   The first-load screen appears while the network is slow by definition, so its mark must
   not be a separate request that arrives after the screen does. A 96px-tall PNG (2x the
   44px it is drawn at) is ~3.4 KB; base64 in the HTML costs ~9 KB per page for both themes.

     node tools/make-preloader-mark.mjs */

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "components/chrome/preloaderMark.ts");

async function encode(file) {
  const png = await sharp(path.join(ROOT, file)).resize({ height: 96 }).png({ compressionLevel: 9, palette: true }).toBuffer();
  const { width, height } = await sharp(png).metadata();
  return { uri: `data:image/png;base64,${png.toString("base64")}`, width, height, bytes: png.length };
}

const light = await encode("public/assets/brand/swh-logo-ink.png"); // ink S — light theme
const dark = await encode("public/assets/brand/swh-logo.png"); // off-white S — dark theme

await writeFile(
  OUT,
  `/* GENERATED by tools/make-preloader-mark.mjs from public/assets/brand/swh-logo-ink.png
   (light theme) and swh-logo.png (dark theme). Do not edit — re-run the script. */

export const PRELOADER_MARK = {
  light: "${light.uri}",
  dark: "${dark.uri}",
  width: ${light.width},
  height: ${light.height},
} as const;
`,
);
console.log(`wrote ${path.relative(ROOT, OUT)} (${light.bytes} + ${dark.bytes} bytes, ${light.width}x${light.height})`);
